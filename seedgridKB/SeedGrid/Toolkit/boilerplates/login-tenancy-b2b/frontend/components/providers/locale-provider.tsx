const APP_MESSAGES: Record<AppLocale, Record<string, string>> = {
  "en-US": EN_US_MESSAGES,
  "pt-BR": PT_BR_MESSAGES,
  "pt-PT": PT_PT_MESSAGES,
  fr: FR_MESSAGES,
  es: ES_MESSAGES,
};

const COMPONENT_MESSAGES: Record<AppLocale, Record<string, string>> = {
  "en-US": componentsMessagesEnUs,
  "pt-PT": componentsMessagesPtPt,
  "pt-BR": componentsMessagesPtBr,
  fr: componentsMessagesFr,
  es: componentsMessagesEs,
};

const LocaleContext = createContext<LocaleContextValue | null>(null);

function normalizeLocale(input?: string): AppLocale {
  if (input === "pt-PT" || input === "pt-BR" || input === "fr" || input === "es") return input;
  return "en-US";
}

/**
 * A preferencia de idioma mora no `localStorage`, que so' existe no cliente.
 *
 * Ler isso no inicializador do `useState` fazia o PRIMEIRO render do cliente divergir do HTML
 * que o servidor mandou sempre que o idioma guardado era diferente do default — e como o idioma
 * atravessa o shell inteiro, a divergencia aparecia em TODA tela (`Minified React error #418`).
 * O custo nao e' so' o log: o React descarta o HTML do servidor e re-renderiza a arvore toda,
 * o que atrasa a primeira pintura e faz o conteudo piscar.
 *
 * `useSyncExternalStore` existe exatamente para este caso: hidrata com o snapshot do SERVIDOR
 * (aqui, "nao ha' preferencia" -> `defaultLocale`) e so' depois da hidratacao troca para o valor
 * do cliente, sem divergencia nenhuma.
 */
const localeListeners = new Set<() => void>();

/** Fallback para navegador com storage bloqueado: o idioma vale so' para esta aba. */
let memoryLocale: string | null = null;

function subscribeLocale(onStoreChange: () => void): () => void {
  localeListeners.add(onStoreChange);
  // `storage` so' dispara para as OUTRAS abas; a propria aba e' notificada por `localeListeners`.
  window.addEventListener("storage", onStoreChange);
  return () => {
    localeListeners.delete(onStoreChange);
    window.removeEventListener("storage", onStoreChange);
  };
}

function readStoredLocale(): string | null {
  try {
    return window.localStorage.getItem(STORAGE_KEY) ?? memoryLocale;
  } catch {
    return memoryLocale;
  }
}

/** Snapshot do servidor: nunca ha' preferencia la', entao o provider cai no `defaultLocale`. */
function readServerLocale(): string | null {
  return null;
}

function writeStoredLocale(next: AppLocale) {
  memoryLocale = next;
  try {
    window.localStorage.setItem(STORAGE_KEY, next);
  } catch {
    // ignore: fica so' em memoria
  }
  localeListeners.forEach((listener) => listener());
}

export function LocaleProvider({
  children,
  defaultLocale = "en-US",
}: {
  readonly children: ReactNode;
  readonly defaultLocale?: AppLocale;
}) {
  const stored = useSyncExternalStore(subscribeLocale, readStoredLocale, readServerLocale);
  const locale = stored ? normalizeLocale(stored) : defaultLocale;

  useEffect(() => {
    setComponentsI18n({
      locale,
      messages: COMPONENT_MESSAGES[locale] ?? componentsMessagesEnUs,
    });
  }, [locale]);

  const value = useMemo<LocaleContextValue>(
    () => ({
      locale,
      // Persiste so' na escolha EXPLICITA do operador. Gravar no mount (como antes) apagava a
      // preferencia com o default antes mesmo de o cliente ter chance de le-la.
      setLocale: (next) => writeStoredLocale(next),
      t: (key, fallback) => APP_MESSAGES[locale][key] ?? APP_MESSAGES["en-US"][key] ?? fallback ?? key,
    }),
    [locale],
  );

  return (
    <LocaleContext.Provider value={value}>
      <SgComponentsI18nProvider
        locale={locale}
        messages={COMPONENT_MESSAGES[locale] ?? componentsMessagesEnUs}
      >
        {children}
      </SgComponentsI18nProvider>
    </LocaleContext.Provider>
  );
}

export function useLocale() {
  const context = useContext(LocaleContext);
  if (!context) {
    throw new Error("useLocale must be used within LocaleProvider");
  }

  return context;
}
